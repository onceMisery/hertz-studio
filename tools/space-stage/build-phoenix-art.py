"""Pack the locally supplied phoenix cutout for synchronous, offline scene creation.
Run with Python + Pillow after editing src/scenes/assets/phoenix-reference.png.
The source artwork was supplied by the user; the code license does not relicense it.
"""
from pathlib import Path
from PIL import Image
import base64, hashlib, json, zlib
folder = Path(__file__).resolve().parent / 'src/scenes/assets'
source = folder / 'phoenix-reference.png'
image = Image.open(source).convert('RGBA')
# An RGB palette and a separate alpha plane preserve soft flames at modest size.
rgb = image.convert('RGB')
clear = Image.new('RGB', image.size)
clear.paste(rgb, mask=image.getchannel('A').point(lambda x: 255 if x > 2 else 0))
indexed = clear.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
planes = indexed.tobytes() + image.getchannel('A').tobytes()
compressed = base64.b64encode(zlib.compress(planes, 9)).decode()
module = '// Generated by build-phoenix-art.py from the user-supplied cutout.\n'
module += '// Artwork provenance: assets/README.md.\n'
module += 'export const phoenixArt = ' + json.dumps({'width':image.width,'height':image.height,'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'palette':indexed.getpalette(),'planes':compressed}, separators=(',',':')) + ';\n'
# newline='\n'：这个字节内容会被 .build-manifest.json 按 sha256 钉住，而 .gitattributes 已把
# tools/*-stage/src/** 钉成 eol=lf。Windows 上 write_text 默认把 \n 写成 \r\n，磁盘字节就与
# CI 检出的 blob 差出换行符，check-release-ui.js 的 hash 比对只在 Linux 上红。
(folder / 'phoenix-reference-data.js').write_text(module, encoding='utf-8', newline='\n')
print(f'Phoenix artwork: {image.width} x {image.height}; {len(compressed)} base64 bytes')
